def setup_page(doc):
    """ตั้งค่าหน้ากระดาษ A4, ฟอนต์ไทยของ style Normal และ footer เลขหน้า"""
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.2)
    sec.top_margin, sec.bottom_margin = Cm(2.0), Cm(2.0)

    normal = doc.styles["Normal"]
    normal.font.name = FONT
    normal.font.size = Pt(BASE_PT)
    _set_fonts(normal.element.get_or_add_rPr(), size_pt=BASE_PT)
    lang = OxmlElement("w:lang")
    lang.set(qn("w:val"), "en-US")
    lang.set(qn("w:bidi"), "th-TH")
    normal.element.get_or_add_rPr().append(lang)

    footer = sec.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run(footer, "GoAlong  |  ข้อกำหนดคุณลักษณะของระบบ Fameline Dock Queue  |  หน้า ", size=8.5, color=GREY)
    add_page_number(footer)


def title_block(doc):
    """หัวเอกสาร: ชื่อเอกสาร ชื่อระบบ และบรรทัดอ้างอิงใบเสนอราคา"""
    para(doc, "ข้อกำหนดคุณลักษณะของระบบ (Program Specification)", bold=True, size=17, color=GREEN,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=2)
    para(doc, "ระบบจองคิวรับ-ส่งสินค้าหน้าคลัง — Fameline Dock Queue", bold=True, size=12.5, color=DARK,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=6)
    p = para(doc, align=WD_ALIGN_PARAGRAPH.CENTER, after=2)
    run(p, "เอกสารแนบใบเสนอราคาเลขที่ ", size=9.5, color=GREY)
    run(p, "[ระบุ]", size=9.5, draft=True)
    run(p, f"   ·   ฉบับที่ {DOC_VERSION}   ·   วันที่ {DOC_DATE}", size=9.5, color=GREY)
    para(doc, "จัดทำโดย GoAlong  ·  จัดทำสำหรับ Fameline", size=9.5, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=8)


