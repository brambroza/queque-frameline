def _set_fonts(rpr, size_pt=None, bold=None):
    """Thai is a complex script in Word: it needs w:cs font, w:szCs and w:bCs, not only the Latin ones."""
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = OxmlElement("w:rFonts")
        rpr.insert(0, fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        fonts.set(qn(attr), FONT)
    if size_pt is not None:
        for tag in ("w:sz", "w:szCs"):
            el = rpr.find(qn(tag))
            if el is None:
                el = OxmlElement(tag)
                rpr.append(el)
            el.set(qn("w:val"), str(int(size_pt * 2)))
    if bold is not None:
        for tag in ("w:b", "w:bCs"):
            el = rpr.find(qn(tag))
            if el is None:
                el = OxmlElement(tag)
                rpr.append(el)
            el.set(qn("w:val"), "1" if bold else "0")


def run(par, text, *, bold=False, size=None, color=None, italic=False, draft=False):
    """Add a run with Thai-safe formatting. draft=True highlights it yellow for internal review."""
    r = par.add_run(text)
    _set_fonts(r._r.get_or_add_rPr(), size_pt=size or BASE_PT, bold=bold)
    r.italic = italic
    if color is not None:
        r.font.color.rgb = color
    if draft and HIGHLIGHT_DRAFT:
        r.font.highlight_color = WD_COLOR_INDEX.YELLOW
    return r


def para(doc, text="", *, bold=False, size=None, color=None, align=None, after=6, before=0, draft=False, italic=False):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.25
    if align is not None:
        p.alignment = align
    if text:
        run(p, text, bold=bold, size=size, color=color, draft=draft, italic=italic)
    return p


def h1(doc, number, text):
    p = para(doc, before=14, after=8)
    p.paragraph_format.keep_with_next = True
    run(p, f"{number}. {text}", bold=True, size=15, color=GREEN)
    ppr = p._p.get_or_add_pPr()
    border = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    for k, v in (("w:val", "single"), ("w:sz", "8"), ("w:space", "4"), ("w:color", "0B7A4B")):
        bottom.set(qn(k), v)
    border.append(bottom)
    ppr.append(border)
    return p


def h2(doc, text):
    p = para(doc, before=10, after=4)
    p.paragraph_format.keep_with_next = True
    run(p, text, bold=True, size=12, color=DARK)
    return p


def bullets(doc, items, *, draft=False):
    for item in items:
        p = para(doc, after=3)
        p.paragraph_format.left_indent = Cm(0.9)
        p.paragraph_format.first_line_indent = Cm(-0.45)
        run(p, "•  ", color=GREEN, bold=True)
        if isinstance(item, tuple):
            run(p, item[0], bold=True)
            run(p, item[1], draft=draft)
        else:
            run(p, item, draft=draft)


def steps(doc, items):
    for i, (title, detail) in enumerate(items, 1):
        p = para(doc, after=4)
        p.paragraph_format.left_indent = Cm(0.9)
        p.paragraph_format.first_line_indent = Cm(-0.9)
        run(p, f"{i})  ", bold=True, color=GREEN)
        run(p, title, bold=True)
        run(p, " — " + detail)


def shade(cell, hex_fill):
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tcpr.append(shd)


def cell_text(cell, text, *, bold=False, color=None, align=None, size=None, draft=False):
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.line_spacing = 1.15
    if align is not None:
        p.alignment = align
    run(p, text, bold=bold, color=color, size=size or 9.5, draft=draft)


def apply_widths(t, widths):
    """Set gridCol + cell widths and a fixed layout so Word and LibreOffice agree on column sizes."""
    t.autofit = False
    for i, w in enumerate(widths):
        t.columns[i].width = Cm(w)
        for row in t.rows:
            row.cells[i].width = Cm(w)
    for row in t.rows:
        trpr = row._tr.get_or_add_trPr()
        cant = OxmlElement("w:cantSplit")
        cant.set(qn("w:val"), "true")
        trpr.append(cant)


def table(doc, header, rows, widths, *, draft_cols=(), right_cols=(), bold_last=False):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, text in enumerate(header):
        c = t.rows[0].cells[i]
        shade(c, "0B7A4B")
        cell_text(c, text, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF), align=WD_ALIGN_PARAGRAPH.CENTER)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        last = bold_last and ri == len(rows) - 1
        for i, text in enumerate(row):
            if ri % 2 == 1 and not last:
                shade(cells[i], "F3F7F5")
            if last:
                shade(cells[i], "E3F1EA")
            cell_text(cells[i], text, bold=last, draft=i in draft_cols,
                      align=WD_ALIGN_PARAGRAPH.RIGHT if i in right_cols else None)
    apply_widths(t, widths)
    # repeat header row on page break
    trpr = t.rows[0]._tr.get_or_add_trPr()
    hdr = OxmlElement("w:tblHeader")
    hdr.set(qn("w:val"), "true")
    trpr.append(hdr)
    para(doc, after=4)
    return t


def figure(doc, number, filename, caption, width_cm=16.0):
    p = para(doc, align=WD_ALIGN_PARAGRAPH.CENTER, after=2, before=4)
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(str(SHOTS / filename), width=Cm(width_cm))
    cap = para(doc, align=WD_ALIGN_PARAGRAPH.CENTER, after=10)
    run(cap, f"ภาพที่ {number}  ", bold=True, size=9, color=GREEN)
    run(cap, caption, size=9, color=GREY)


def figure_row(doc, start_number, items, width_cm=5.1):
    """Several phone screenshots side by side. items = [(filename, caption), ...]"""
    t = doc.add_table(rows=2, cols=len(items))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, (filename, caption) in enumerate(items):
        p = t.rows[0].cells[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(str(SHOTS / filename), width=Cm(width_cm))
        c = t.rows[1].cells[i].paragraphs[0]
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run(c, f"ภาพที่ {start_number + i}  ", bold=True, size=9, color=GREEN)
        run(c, caption, size=9, color=GREY)
    para(doc, after=8)


def flow(doc, boxes, fill="E3F1EA"):
    """One row of process boxes separated by arrows."""
    cols = len(boxes) * 2 - 1
    t = doc.add_table(rows=1, cols=cols)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    box_w = (16.5 - 0.7 * (len(boxes) - 1)) / len(boxes)
    for i in range(cols):
        c = t.rows[0].cells[i]
        if i % 2 == 0:
            title, detail = boxes[i // 2]
            shade(c, fill)
            c.width = Cm(box_w)
            p = c.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(4)
            run(p, title, bold=True, size=9.5, color=GREEN)
            p2 = c.add_paragraph()
            p2.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p2.paragraph_format.space_after = Pt(4)
            run(p2, detail, size=8.5, color=DARK)
        else:
            c.width = Cm(0.7)
            p = c.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run(p, "▶", size=10, color=GREEN)
            c.vertical_alignment = 1
    apply_widths(t, [box_w if i % 2 == 0 else 0.7 for i in range(cols)])
    para(doc, after=4)


def note(doc, text, *, fill="FFF7E0"):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]
    shade(c, fill)
    c.width = Cm(16.5)
    cell_text(c, text, size=9.5)
    apply_widths(t, [16.5])
    para(doc, after=6)


def page_break(doc):
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def add_page_number(par):
    for kind, text in (("begin", None), (None, "PAGE"), ("end", None)):
        r = par.add_run()
        _set_fonts(r._r.get_or_add_rPr(), size_pt=8.5)
        if kind:
            el = OxmlElement("w:fldChar")
            el.set(qn("w:fldCharType"), kind)
        else:
            el = OxmlElement("w:instrText")
            el.set(qn("xml:space"), "preserve")
            el.text = text
        r._r.append(el)


