/**
 * Content of the five user manuals. Each manual is a list of A4 pages; a page is
 * { eyebrow, title, lead, html }. Screenshots live in screenshots/<role>/ and are
 * produced by capture_manual.mjs — keep the file names in sync.
 */

/** Numbered step list. */
const steps = (items) => `<ol class="steps">${items.map((i) => `<li>${i}</li>`).join('')}</ol>`;
/** Green "หมายเหตุ" callout. */
const note = (html, label = 'หมายเหตุ') => `<div class="note"><b>${label}</b> · ${html}</div>`;
/** Amber "ข้อควรระวัง" callout. */
const warn = (html) => `<div class="note warn"><b>ข้อควรระวัง</b> · ${html}</div>`;
/** Figure card. kind: wide | dialog | pair | phones | crop (crop needs height in mm). */
const fig = (kind, srcs, { h, cls = '' } = {}) => {
  const img = (s) => {
    const tag = `<img src="screenshots/${s}.png"${h && kind === 'dialog' ? ` style="max-height:${h}mm"` : ''}>`;
    // With a height, every kind but `dialog` shows the top of the picture and clips the rest.
    return h && kind !== 'dialog' ? `<div class="clip" style="max-height:${h}mm">${tag}</div>` : tag;
  };
  return `<div class="fig ${kind} ${cls}">${[].concat(srcs).map(img).join('')}</div>`;
};
const cap = (t) => `<p class="cap">${t}</p>`;
/** Simple table. */
const table = (head, rows, cls = '') => `<table class="${cls}"><thead><tr>${head.map((h) => `<th>${h}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table>`;
const k = (t) => `<span class="k">${t}</span>`;
const cards = (list) => `<div class="cards">${list.map(([title, items, plain]) => `<div class="card ${plain ? 'plain' : ''}"><h3>${title}</h3><ul>${items.map((i) => `<li>${i}</li>`).join('')}</ul></div>`).join('')}</div>`;

